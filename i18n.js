  const buttons = [...document.querySelectorAll('[data-lang]')];
  let language = 'ru';

  function translate(id, russian) {
    return language === 'en' ? english[id] ?? russian : russian;
  }

  function paint(value) {
    language = value === 'en' ? 'en' : 'ru';
    document.documentElement.lang = language;
    for (const {element, attribute, id, russian} of entries) {
      const value = translate(id, russian);
      if (attribute) element.setAttribute(attribute, value);
      else element.textContent = value;
    }
    for (const button of buttons) button.setAttribute('aria-pressed', String(button.dataset.lang === language));
    document.dispatchEvent(new Event('portfolio:language'));
  }

  function restore() {
    try { paint(localStorage.getItem(key)); }
    catch { paint(language); }
  }

  for (const button of buttons) button.addEventListener('click', () => {
    if (language === button.dataset.lang) return;
    paint(button.dataset.lang);
    try { localStorage.setItem(key, language); } catch {}
  });
  window.addEventListener('storage', event => {
    if (event.key === key) paint(event.newValue);
  });
  window.addEventListener('pageshow', event => { if (event.persisted) restore(); });
  restore();

  return {translate, get language() { return language; }};
